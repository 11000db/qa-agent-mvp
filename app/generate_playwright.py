import json
import sys
from pathlib import Path

DEFAULT_TEST_CASE_PATH = Path("sample_outputs/login_test_case.json")
DEFAULT_OUTPUT_DIR = Path("playwright")
BASE_URL = "https://the-internet.herokuapp.com"


def read_json_file(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


# Day 26 추가: 입력값이 생성 코드 문법을 깨지 않도록 처리
# - 따옴표가 들어간 기능명 → JS 문자열 리터럴로 이스케이프
# - 줄바꿈이 들어간 스텝 → 한 줄 주석 밖으로 코드가 새어 나가지 않게 한 줄로 합침
def js_string(value) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def comment_text(value) -> str:
    return " ".join(str(value).split()).replace("*/", "* /")


def as_list(value) -> list:
    return value if isinstance(value, list) else []


def generate_playwright_code(data: dict) -> str:
    feature_name = data.get("feature_name") or "Unknown Feature"
    test_steps = as_list(data.get("test_steps"))
    expected_results = as_list(data.get("expected_results"))
    negative_cases = as_list(data.get("negative_cases"))
    edge_cases = as_list(data.get("edge_cases"))
    priority = data.get("priority", "-")
    risk_level = data.get("risk_level", "-")

    lines = []

    # 헤더
    lines.append(f"import {{ test, expect }} from '@playwright/test';")
    lines.append(f"")
    lines.append(f"/**")
    lines.append(f" * Feature: {comment_text(feature_name)}")
    lines.append(f" * Priority: {comment_text(priority)}")
    lines.append(f" * Risk Level: {comment_text(risk_level)}")
    lines.append(f" * Auto-generated by QA Agent MVP")
    lines.append(f" */")
    lines.append(f"")
    lines.append(f"const BASE_URL = '{BASE_URL}';")
    lines.append(f"")

    # Happy Path 테스트
    lines.append(f"test.describe({js_string(feature_name)}, () => {{")
    lines.append(f"")
    lines.append(f"  test('Happy Path - 정상 동작 확인', async ({{ page }}) => {{")
    lines.append(f"    await page.goto(BASE_URL);")
    lines.append(f"")
    lines.append(f"    // Test Steps")
    for step in test_steps:
        lines.append(f"    // {comment_text(step)}")
    lines.append(f"")
    lines.append(f"    // Expected Results")
    for result in expected_results:
        lines.append(f"    // TODO: {comment_text(result)}")
    lines.append(f"  }});")
    lines.append(f"")

    # Negative Cases
    if negative_cases:
        lines.append(f"  test.describe('Negative Cases', () => {{")
        lines.append(f"")
        for i, case in enumerate(negative_cases, 1):
            lines.append(f"    test('Negative {i}', async ({{ page }}) => {{")
            lines.append(f"      await page.goto(BASE_URL);")
            lines.append(f"      // {comment_text(case)}")
            lines.append(f"      // TODO: implement")
            lines.append(f"    }});")
            lines.append(f"")
        lines.append(f"  }});")
        lines.append(f"")

    # Edge Cases
    if edge_cases:
        lines.append(f"  test.describe('Edge Cases', () => {{")
        lines.append(f"")
        for i, case in enumerate(edge_cases, 1):
            lines.append(f"    test('Edge {i}', async ({{ page }}) => {{")
            lines.append(f"      await page.goto(BASE_URL);")
            lines.append(f"      // {comment_text(case)}")
            lines.append(f"      // TODO: implement")
            lines.append(f"    }});")
            lines.append(f"")
        lines.append(f"  }});")
        lines.append(f"")

    lines.append(f"}});")

    return "\n".join(lines)


def main() -> None:
    test_case_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_TEST_CASE_PATH

    if not test_case_path.exists():
        raise FileNotFoundError(f"테스트 케이스 파일이 없습니다: {test_case_path}")

    data = read_json_file(test_case_path)

    playwright_code = generate_playwright_code(data)

    stem = test_case_path.stem.replace("_test_case", "")
    output_path = DEFAULT_OUTPUT_DIR / f"{stem}.spec.ts"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(playwright_code, encoding="utf-8")

    print(f"Playwright 코드 생성 완료: {output_path}")


if __name__ == "__main__":
    main()