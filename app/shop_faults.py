FAULT_IDS = [f[0] for f in FAULTS]


def injection_enabled() -> bool:
    return os.getenv("SHOP_FAULT_INJECTION") == "1"


def active_faults(headers) -> set:
    if not injection_enabled():
        return set()
    raw = headers.get(FAULT_HEADER, "")
    return {f.strip() for f in raw.split(",") if f.strip() in FAULT_IDS}
